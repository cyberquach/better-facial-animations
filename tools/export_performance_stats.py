"""Export a trained student's normalization to the native runtime header.

Usage: python tools/export_performance_stats.py normalization.npz output.h
The paired ONNX/provenance must be updated and parity rechecked together.
"""
import sys
from pathlib import Path
import numpy as np

ARRAYS = [('mel_mean', 'kMelMean', 80), ('mel_std', 'kMelStd', 80),
          ('target_mean', 'kTargetMean', 73), ('target_std', 'kTargetStd', 73)]
PER_LINE = 4

stats = np.load(sys.argv[1])
with Path(sys.argv[2]).open('w') as f:
    f.write('// Frozen performance-model normalization; provenance in '
            'dist/performance-model.json.\n'
            '// Generated by tools/export_performance_stats.py.\n'
            '#ifndef INCLUDE_A2F_INFERENCE_PERFORMANCE_STATS_H_\n'
            '#define INCLUDE_A2F_INFERENCE_PERFORMANCE_STATS_H_\n\n'
            'namespace a2f::performance {\n\n')
    for key, name, count in ARRAYS:
        values = stats[key]
        assert values.shape == (count,) and np.isfinite(values).all()
        if key.endswith('std'):
            assert (values > 0).all()
        rows = [', '.join(format(float(v), '.9e') + 'f'
                          for v in values[i:i + PER_LINE])
                for i in range(0, len(values), PER_LINE)]
        f.write('inline constexpr float ' + name + '[] = {\n    ' +
                ',\n    '.join(rows) + '};\n\n')
    f.write('}  // namespace a2f::performance\n\n'
            '#endif  // INCLUDE_A2F_INFERENCE_PERFORMANCE_STATS_H_\n')
